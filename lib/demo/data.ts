import type { CapaAction, Incident, Task } from "@/lib/types";

const DAY = 86_400_000;

function ago(now: number, days: number, hour = 8) {
  const date = new Date(now - days * DAY);
  date.setUTCHours(hour, 12, 0, 0);
  return date.toISOString();
}

function dateOnly(now: number, days: number) {
  return new Date(now + days * DAY).toISOString().slice(0, 10);
}

function capa(
  now: number,
  assigneeId: string,
  assigneeName: string,
  status: CapaAction["status"],
  createdDaysAgo: number,
  dueInDays: number,
  notes: string,
  doneAfterDays?: number
): CapaAction {
  return {
    assigneeId,
    assigneeName,
    dueDate: dateOnly(now, dueInDays),
    status,
    notes,
    updatedAt: ago(now, doneAfterDays !== undefined ? createdDaysAgo - doneAfterDays : Math.max(0, createdDaysAgo - 1), 14),
  };
}

type Draft = Omit<Incident, "mediaUrls" | "source" | "status" | "capa"> & Partial<Pick<Incident, "status" | "capa">>;

function incident(draft: Draft): Incident {
  return { mediaUrls: [], source: "report", status: "open", capa: null, ...draft };
}

