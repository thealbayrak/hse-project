"use client";

import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { buildAmlNoticeModel, openAmlNotice } from "@/lib/compliance/aml-33a";
import { useLanguage } from "@/lib/i18n/LanguageContext";
import type { Incident, Site } from "@/lib/types";

export function AmlNoticeDialog({
  incident,
  site,
  open,
  onClose,
}: {
  incident: Incident | null;
  site: Site | null;
  open: boolean;
  onClose: () => void;
}) {
  const { t } = useLanguage();
  if (!incident) return null;
  const model = buildAmlNoticeModel(incident, site);

  return (
    <Dialog open={open} onOpenChange={(next) => !next && onClose()}>
      <DialogContent
        className="aml-notice-dialog z-[60] max-h-[92dvh] overflow-y-auto bg-white text-slate-900 sm:max-w-3xl"
        showCloseButton
      >
        <DialogHeader className="no-print">
          <DialogTitle className="text-slate-950">AML 3:3a notice</DialogTitle>
          <DialogDescription className="text-slate-600">
            Print-ready statutory template. Use Print / Save PDF for a paper-white A4 copy.
          </DialogDescription>
        </DialogHeader>

        <article id="aml-33a-sheet" className="border border-slate-900 bg-white p-5 text-slate-950">
          <p className="text-[11px] font-bold tracking-[0.16em] text-red-800">
            ARBETSMILJÖVERKET · FORMULÄR FÖR ANMÄLAN
          </p>
          <h2 className="mt-1 text-lg leading-snug font-semibold">
            Anmälan om allvarligt tillbud eller arbetsskada (Arbetsmiljölagen 3 kap. 3 a §)
          </h2>
          <p className="mt-1 text-xs text-slate-600">
            Supporting notice generated by SiteSafety Nordic · Ref. {model.reference}
          </p>
          <div className="mt-4 border-2 border-red-800 bg-red-50 p-3 text-sm text-red-900">
            Allvarliga tillbud och olycksfall ska anmälas till Arbetsmiljöverket utan dröjsmål.
            Severe accidents and dangerous near-misses (tillbud) must be notified to Arbetsmiljöverket
            without delay.
          </div>

          <section className="mt-5 border border-slate-900">
            <h3 className="bg-slate-950 px-3 py-2 text-xs font-semibold tracking-wide text-white uppercase">
              A. Arbetsställe &amp; verksamhet
            </h3>
            <Field label="Arbetsställe" hint="Site name" value={model.siteName} />
            <Field label="Verksamhet / bolag" hint="Organization" value={model.organizationName} />
            <Field label="Organisationsnummer" hint="Organization number" value={model.organizationNumber} />
            <Field label="Adress" hint="Address" value={model.address} />
            <Field label="Ort" hint="City" value={model.city} />
          </section>

          <section className="mt-4 border border-slate-900">
            <h3 className="bg-slate-950 px-3 py-2 text-xs font-semibold tracking-wide text-white uppercase">
              B. Händelseförlopp
            </h3>
            <Field label="Datum" hint="Date" value={model.eventDate} />
            <Field label="Klockslag" hint="Time (Europe/Stockholm)" value={model.eventTime} />
            <Field label="Plats på arbetsstället" hint="Specific location" value={model.specificLocation} />
            <Field label="Typ av händelse" hint="Incident type" value={model.incidentType} />
            <Field label="Riskkategori" hint="Category" value={model.category} />
            <Field label="Allvarlighetsgrad" hint="Severity" value={model.severity} />
            <div className="border-t border-slate-900 p-3 text-sm leading-relaxed">
              <p className="font-semibold">Detaljerad redogörelse / Sequence of events</p>
              <p className="mt-2 whitespace-pre-wrap">{model.sequenceOfEvents}</p>
            </div>
          </section>

          <section className="mt-4 border border-slate-900">
            <h3 className="bg-slate-950 px-3 py-2 text-xs font-semibold tracking-wide text-white uppercase">
              C. Riskbedömning &amp; vidtagna åtgärder
            </h3>
            <Field label="Omedelbara åtgärder" hint="Immediate containment" value={model.immediateContainment} />
            <Field label="Bedömd orsak" hint="Root cause / risk" value={model.rootCause} />
            <Field label="CAPA-ansvarig" hint="Assigned owner" value={model.capaAssignee} />
            <Field label="Förfallodatum" hint="Due date" value={model.capaDueDate} />
            <Field label="Status" hint="CAPA status" value={model.capaStatus} />
            <div className="border-t border-slate-900 p-3 text-sm leading-relaxed">
              <p className="font-semibold">CAPA-åtgärder / Assigned actions</p>
              <p className="mt-2 whitespace-pre-wrap">{model.capaNotes}</p>
            </div>
          </section>

          <p className="mt-4 text-[11px] text-slate-600">
            Detta underlag stöder anmälan enligt AML 3 kap. 3 a §. Den officiella anmälan görs hos
            Arbetsmiljöverket.
          </p>
        </article>

        <DialogFooter className="no-print bg-white">
          <Button variant="outline" className="h-12 text-slate-900" onClick={onClose}>
            {t("buttons.close")}
          </Button>
          <Button
            variant="outline"
            className="h-12 text-slate-900"
            onClick={() => openAmlNotice(model)}
          >
            {t("buttons.openA4")}
          </Button>
          <Button className="h-12" onClick={() => window.print()}>
            {t("buttons.printPdf")}
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}

function Field({ label, hint, value }: { label: string; hint: string; value: string }) {
  return (
    <div className="grid grid-cols-[34%_1fr] border-t border-slate-900 text-sm">
      <div className="bg-slate-50 px-3 py-2">
        <p className="text-[11px] font-semibold tracking-wide text-slate-600 uppercase">{label}</p>
        <p className="text-[11px] text-slate-500">{hint}</p>
      </div>
      <div className="px-3 py-2 font-medium">{value}</div>
    </div>
  );
}
